// Writes apps/extension/lib/categories.js from the one categoriser in
// packages/shared/src/categories.ts. The extension has no build step and cannot import
// TypeScript, so it gets a generated copy of the site lists and the host rule.
//
//   pnpm categories:extension
//
// apps/api/src/patterns/categories.test.ts fails when the copy and the shared lists drift apart.

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SITE_BRANDS, SITE_LISTS } from "@michael/shared";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = resolve(repo, "apps/extension/lib/categories.js");

const source = `// GENERATED by apps/api/scripts/extension-categories.ts from packages/shared/src/categories.ts.
// Do not edit: change the shared lists and run \`pnpm categories:extension\`.
// The same host gets the same category here, in the collector and in the API.

export const SITE_LISTS = ${JSON.stringify(SITE_LISTS, null, 2)};

export const SITE_BRANDS = ${JSON.stringify(SITE_BRANDS, null, 2)};

const SECOND_LEVEL_ENDINGS = new Set(["co", "com", "org", "net", "gov", "edu", "ac"]);

const CATEGORY_OF = new Map(
  Object.entries(SITE_LISTS).flatMap(([category, hosts]) => hosts.map((host) => [host, category])),
);

/**
 * The category of a host, or undefined when the site is not on the list. The longest listed
 * ending wins ("music.youtube.com" is music, "youtube.com" is video), then a listed brand under
 * any country ending ("amazon.de", "amazon.co.uk").
 */
export function categoryFor(input) {
  const host = String(input ?? "")
    .trim()
    .toLowerCase()
    .replace(/^www\\./, "")
    .replace(/\\.$/, "");
  if (!host) return undefined;
  const labels = host.split(".");
  for (let i = 0; i < labels.length; i++) {
    const category = CATEGORY_OF.get(labels.slice(i).join("."));
    if (category) return category;
  }
  if (labels.length >= 2) {
    const last = labels.length - 1;
    const second = labels[last - 1] ?? "";
    const brand = labels.length >= 3 && SECOND_LEVEL_ENDINGS.has(second) ? labels[last - 2] : second;
    const category = brand && Object.hasOwn(SITE_BRANDS, brand) ? SITE_BRANDS[brand] : undefined;
    if (category) return category;
  }
  return undefined;
}
`;

writeFileSync(out, source);
spawnSync("pnpm", ["exec", "biome", "format", "--write", out], { cwd: repo, stdio: "inherit" });
console.log(`wrote ${out}`);
